// ---------------- Site (crawl) ----------------

/** Terminal-friendly (plain, no colour) crawl-audit summary. Pure. */
export function formatSiteReport(site: SiteReport): string {
  const L: string[] = [];
  L.push("");
  L.push(`◆ lacspace-inspect — site audit of ${site.seed}`);
  L.push(`  ${site.pageCount} page(s) · average ${site.averageGrade} (${site.averageScore}/100)`);
  L.push("");
  L.push("  Leaderboard");
  for (const e of site.leaderboard) {
    L.push(`    ${e.grade}  ${String(e.score).padStart(3)}  ${e.url}`);
  }
  if (site.commonIssues.length) {
    L.push("");
    L.push("  Most common issues");
    for (const i of site.commonIssues.slice(0, 8)) {
      L.push(`    ${ICON[i.status]} ×${i.count}  ${i.id} — ${i.message}`);
    }
  }
  if (site.duplicateTitles.length) {
    L.push("");
    L.push("  Duplicate <title> across pages");
    for (const d of site.duplicateTitles.slice(0, 5)) L.push(`    "${d.value}" — ${d.urls.length} pages`);
  }
  if (site.duplicateDescriptions.length) {
    L.push("");
    L.push("  Duplicate meta description across pages");
    for (const d of site.duplicateDescriptions.slice(0, 5)) L.push(`    "${d.value.slice(0, 60)}…" — ${d.urls.length} pages`);
  }
  if (site.brokenInternalLinks.length) {
    L.push("");
    L.push(`  Broken internal links (${site.brokenInternalLinks.length})`);
    for (const b of site.brokenInternalLinks.slice(0, 10)) L.push(`    ${b.status} ${b.to}  (on ${b.from})`);
  }
  L.push("");
  return L.join("\n");
}

/** Crawl-audit summary as Markdown (PR-comment ready). Pure. */
export function formatSiteMarkdown(site: SiteReport): string {
  const L: string[] = [];
  L.push(`## ◆ lacspace-inspect — site audit`);
  L.push("");
  L.push(`**Seed:** ${site.seed} · **${site.pageCount} pages** · average \`${site.averageGrade}\` (${site.averageScore}/100)`);
  L.push("");
  L.push("### Leaderboard");
  L.push("");
  L.push("| Grade | Score | URL |");
  L.push("| :---: | ---: | --- |");
  for (const e of site.leaderboard) L.push(`| \`${e.grade}\` | ${e.score} | ${e.url} |`);
  L.push("");
  if (site.commonIssues.length) {
    L.push("### Most common issues");
    L.push("");
    L.push("| Count | Check | Issue |");
    L.push("| ---: | --- | --- |");
    for (const i of site.commonIssues) L.push(`| ${i.count} | \`${i.id}\` | ${i.message} |`);
    L.push("");
  }
  if (site.duplicateTitles.length) {
    L.push("### Duplicate `<title>` across pages");
    L.push("");
    for (const d of site.duplicateTitles) L.push(`- **"${d.value}"** — ${d.urls.length} pages`);
    L.push("");
  }
  if (site.duplicateDescriptions.length) {
    L.push("### Duplicate meta descriptions");
    L.push("");
    for (const d of site.duplicateDescriptions) L.push(`- "${d.value.slice(0, 80)}…" — ${d.urls.length} pages`);
    L.push("");
  }
  if (site.brokenInternalLinks.length) {
    L.push(`### Broken internal links (${site.brokenInternalLinks.length})`);
    L.push("");
    for (const b of site.brokenInternalLinks) L.push(`- \`${b.status}\` ${b.to} — linked from ${b.from}`);
    L.push("");
  }
  return L.join("\n");
}

// ---------------- Batch leaderboard ----------------

/** A simple ranked table for `--input` batch runs. Pure. */
export function formatLeaderboard(entries: { url: string; score: number; grade: Grade }[]): string {
  const sorted = [...entries].sort((a, b) => b.score - a.score || a.url.localeCompare(b.url));
  const L: string[] = ["", "◆ lacspace-inspect — batch leaderboard", ""];
  sorted.forEach((e, i) => L.push(`  ${String(i + 1).padStart(2)}. ${e.grade}  ${String(e.score).padStart(3)}  ${e.url}`));
  L.push("");
  return L.join("\n");
}

// ---------------- Regressions ----------------

/** Render a baseline diff. Pure. */
export function formatRegressions(regs: Regression[]): string {
  if (regs.length === 0) return "  ✓ No regressions against the baseline.";
  const L: string[] = [`  ✗ ${regs.length} regression(s) against the baseline:`];
  for (const r of regs) L.push(`    - [${r.kind}] ${r.message}`);
  return L.join("\n");
}
