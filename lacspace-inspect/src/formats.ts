/**
 * Extra output formats — all **pure** string builders, no colour codes, so they
 * render the same in a file, a PR comment or a browser:
 *
 * - {@link formatMarkdown}  — a single-report Markdown summary (great as a PR comment).
 * - {@link formatHtml}      — a standalone, shareable HTML report.
 * - {@link formatSiteReport}/{@link formatSiteMarkdown} — the crawl-audit rollup.
 * - {@link formatLeaderboard} — the batch (`--input`) table.
 * - {@link formatRegressions} — a `--baseline` diff.
 */
import type { Category, Finding, Grade, Regression, Report, SiteReport } from "./types.js";

const ICON: Record<Finding["status"], string> = { ok: "✓", warn: "▲", fail: "✗", info: "ℹ" };

function badge(grade: Grade | null): string {
  return grade ? `\`${grade}\`` : "`–`";
}

// ---------------- Markdown (single report) ----------------

function mdFinding(f: Finding): string {
  const base = `- ${ICON[f.status]} ${f.message}`;
  const fix = f.fix && (f.status === "warn" || f.status === "fail") ? `\n  - **Fix:** ${f.fix}` : "";
  return base + fix;
}

/** Render a report as Markdown. `verbose` also lists passing checks. */
export function formatMarkdown(report: Report, verbose = false): string {
  const lines: string[] = [];
  lines.push(`## ◆ lacspace-inspect — ${badge(report.grade)} ${report.score}/100`);
  lines.push("");
  lines.push(`**URL:** ${report.url}  `);
  const meta: string[] = [];
  if (report.httpStatus) meta.push(`HTTP ${report.httpStatus}`);
  meta.push(report.https ? "HTTPS" : "HTTP");
  meta.push(`${(report.stats.htmlBytes / 1024).toFixed(0)} KB`);
  if (report.stats.responseTimeMs !== undefined) meta.push(`${report.stats.responseTimeMs} ms`);
  lines.push(`**Audited:** ${report.fetchedAt} · ${meta.join(" · ")}`);
  lines.push("");

  const fails = report.categories.flatMap((c) => c.findings).filter((f) => f.status === "fail").length;
  const warns = report.categories.flatMap((c) => c.findings).filter((f) => f.status === "warn").length;
  lines.push(`> **${fails} failing · ${warns} warning** — overall grade ${badge(report.grade)}`);
  lines.push("");

  lines.push("| Category | Grade | Score |");
  lines.push("| --- | :---: | ---: |");
  for (const c of report.categories) {
    lines.push(`| ${c.title} | ${badge(c.grade)} | ${c.score === null ? "–" : c.score} |`);
  }
  lines.push("");

  for (const c of report.categories) {
    const shown = c.findings.filter((f) => verbose || f.status !== "ok");
    if (shown.length === 0) continue;
    lines.push(`### ${c.title} ${badge(c.grade)}${c.score === null ? "" : ` — ${c.score}/100`}`);
    lines.push("");
    for (const f of shown) lines.push(mdFinding(f));
    lines.push("");
  }

  if (report.tech.length) {
    lines.push(`**Tech:** ${report.tech.join(", ")}`);
    lines.push("");
  }
  lines.push(`<sub>Generated by lacspace-inspect · static HTML audit, not a runtime Lighthouse pass.</sub>`);
  return lines.join("\n");
}

// ---------------- HTML (single report) ----------------

function esc(s: string): string {
  return s.replace(/[&<>"]/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[ch]!));
}
const GRADE_HEX: Record<Grade, string> = { A: "#16a34a", B: "#0891b2", C: "#ca8a04", D: "#ea580c", F: "#dc2626" };
function gradeHex(g: Grade | null): string { return g ? GRADE_HEX[g] : "#94a3b8"; }

/** Render a report as a standalone, shareable HTML document. Pure. */
